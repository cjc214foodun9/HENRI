from __future__ import annotations

import os
from typing import Any, Dict, List, Optional, Sequence, Tuple

import torch

FEATURE_FLAG = "HENRI_ARC_JEPA_TRANSITION_TRAINING"
STATUS_DISABLED = "FEATURE_DISABLED"
STATUS_OK = "OK"
SCHEMA_ID = "henri.jepa-transition-training-arm.v1"

# Transform kinds used for the known-transform training set. Each maps to a
# MacroOption via _transform_via_option (production option path).
TRAIN_KINDS = ("translate_dx", "translate_dy", "rotate90")


def _base_out(task_id: str, **extra: Any) -> Dict[str, Any]:
    """Eligibility telemetry carried by EVERY return path (single source)."""
    out = {
        "schema_id": SCHEMA_ID,
        "transform": task_id,
        "score_eligible": False,
        "diagnostic_only": True,
        "authorizes_rollout": False,
    }
    out.update(extra)
    return out


class JepaTransitionTrainingProbe:
    """Default-OFF R3 transition-training arm harness (production kernels)."""

    def __init__(
        self,
        planner: Any,
        tokenizer: Any,
        psg: Any,
        device: str = "cpu",
        num_blocks: int = 8192,
        block_dim: int = 8,
    ) -> None:
        self.planner = planner
        self.tokenizer = tokenizer
        self.psg = psg
        self.device = device
        self.num_blocks = num_blocks
        self.block_dim = block_dim

    @property
    def enabled(self) -> bool:
        return os.environ.get(FEATURE_FLAG, "0") == "1"

    def status(self) -> Dict[str, Any]:
        return {
            "schema_id": "henri.jepa-transition-training.status.v1",
            "status": STATUS_OK if self.enabled else STATUS_DISABLED,
            "feature_gate": FEATURE_FLAG,
            "device": self.device,
            "score_eligible": False,
            "diagnostic_only": True,
            "authorizes_rollout": False,
        }

    def build_pairs(self, seeds: Sequence[int] = (0, 1, 2)) -> Dict[str, Any]:
        """Build known-transform training pairs as REAL encoder waves.

        For each kind x seed: g_t (single-object 8x8 grid), g_t1 via the
        production MacroOption apply path; waves from the production
        masked-ramp encoder; action wave via psg.option_waves. A pair whose
        option is absent is skipped (recorded), never fabricated.
        """
        from progressive_semantic_grounding_engine import (  # lazy: local CPU import stays light
            MacroOption,
            _apply_option_to_grid,
        )

        pairs: List[Dict[str, Any]] = []
        skipped: List[str] = []
        for kind in TRAIN_KINDS:
            for seed in seeds:
                color = 1 + (seed % 3)
                g = self._single_object_grid(size=8, color=color)
                opt = self._option_for(kind, g)
                g1 = _apply_option_to_grid(g, opt)
                state = self.tokenizer.encode_spatial_grid(g).squeeze(0).to(self.device)
                nxt = self.tokenizer.encode_spatial_grid(g1).squeeze(0).to(self.device)
                waves, labels = self.psg.option_waves(g, [opt])
                if len(waves) == 0:
                    skipped.append(f"{kind}:{seed}")
                    continue
                action_wave = waves[0].to(self.device)
                pairs.append({
                    "kind": kind, "seed": seed, "label": labels[0] if labels else kind,
                    "state": state, "action_wave": action_wave, "next": nxt,
                })
        return {"pairs": pairs, "skipped": skipped}

    @staticmethod
    def _single_object_grid(size: int = 8, color: int = 1) -> List[List[int]]:
        g = [[0] * size for _ in range(size)]
        g[2][3] = g[2][4] = g[3][4] = color
        return g

    @staticmethod
    def _option_for(kind: str, grid: List[List[int]]) -> Any:
        from progressive_semantic_grounding_engine import MacroOption  # lazy
        H, W = len(grid), len(grid[0])
        color = 1
        for row in grid:
            for v in row:
                if v != 0:
                    color = v
        bbox = (0, 0, H - 1, W - 1)
        if kind == "translate_dx":
            return MacroOption(object_id=0, kind="translate", dx=1, dy=0,
                               bbox=bbox, area=0, color=color,
                               description="translate(dx=1, dy=0)")
        if kind == "translate_dy":
            return MacroOption(object_id=0, kind="translate", dx=0, dy=1,
                               bbox=bbox, area=0, color=color,
                               description="translate(dx=0, dy=1)")
        if kind == "rotate90":
            return MacroOption(object_id=0, kind="rotate", angle_deg=90,
                               bbox=bbox, area=0, color=color,
                               description="rotate(90)")
        raise ValueError(kind)

    def train_transition(
        self,
        pair_records: Sequence[Dict[str, Any]],
        k_steps: int = 200,
        lr: float = 0.05,
    ) -> Dict[str, Any]:
        """Online Sagnac training on the LIVE transition (production API)."""
        if not self.enabled:
            return {"status": STATUS_DISABLED, "score_eligible": False,
                    "diagnostic_only": True, "authorizes_rollout": False}
        if not pair_records:
            return {"status": "NO_PAIRS", "score_eligible": False,
                    "diagnostic_only": True, "authorizes_rollout": False}
        history: List[float] = []
        ema_checkpoints: Dict[int, float] = {}
        for step in range(k_steps):
            rec = pair_records[step % len(pair_records)]
            loss = self.planner.train_transition_step(
                rec["state"], rec["action_wave"], rec["next"],
                lr=lr, valence=1.0,
            )
            history.append(float(loss))
            if step % 20 == 0 or step == k_steps - 1:
                ema_checkpoints[step + 1] = float(getattr(self.planner, "loss_ema", 1.0))
        return {
            "status": STATUS_OK,
            "steps": k_steps,
            "num_pairs": len(pair_records),
            "loss_final": float(history[-1]),
            "loss_min": float(min(history)),
            "loss_ema_final": float(getattr(self.planner, "loss_ema", 1.0)),
            "loss_ema_checkpoints": ema_checkpoints,
            "loss_curve_downsampled": history[:: max(1, len(history) // 50)],
            "score_eligible": False,
            "diagnostic_only": True,
            "authorizes_rollout": False,
        }

    def run_arm(
        self,
        arm_id: str,
        grid: List[List[int]],
        pairs: Sequence[Tuple[List[List[int]], List[List[int]]]],
        true_label: str,
        task_id: str,
        boundary_batch: torch.Tensor,
    ) -> Dict[str, Any]:
        """Run ONE arm on ONE transform through the FULL production path."""
        if not self.enabled:
            return _base_out(task_id, status=STATUS_DISABLED, arm=arm_id)
        if self.psg is None or self.planner is None or self.tokenizer is None:
            return _base_out(task_id, status="BLOCKED_MISSING_MACHINERY",
                             arm=arm_id)

        res = self.psg.compile_task_functor(pairs, task_id=f"{arm_id}:{task_id}")
        if getattr(res, "status", STATUS_OK) != STATUS_OK:
            return _base_out(
                task_id, arm=arm_id,
                status=getattr(res, "status", "COMPILE_FAILED"),
                reason=getattr(res, "reason", ""),
            )

        state_wave = self.tokenizer.encode_spatial_grid(grid).squeeze(0).to(self.device)
        goal_wave = self.psg.goal_bind(state_wave)  # functor-bound goal

        options = self.psg.options_from_grid(grid)
        keep = [o for o in options if o.kind in ("translate", "rotate")]
        waves, labels = self.psg.option_waves(grid, keep)
        true_idx = next((i for i, lb in enumerate(labels) if lb == true_label), -1)
        if true_idx < 0:
            return _base_out(task_id, arm=arm_id, status="TRUE_LABEL_ABSENT",
                             labels=labels[:20])

        candidates = list(zip(labels, [w for w in waves]))

        # G2/G3 guards: decomposition + loop/vmap identity from production kernels.
        efe_loop = self.psg.score(state_wave, waves, boundary_batch, goal_wave)
        efe_bat = self.psg.score_batched(state_wave, waves, boundary_batch, goal_wave)
        vmap_agreement = float((efe_loop - efe_bat).abs().max().item())

        # COMPLETE production selection path (incl. T4 explore gate).
        ranked = self.planner.score_actions(
            state_wave, candidates, boundary_batch, goal_wave=goal_wave)
        action, predicted, table, chosen = self.planner.select_action(
            state_wave, candidates, boundary_batch, goal_wave=goal_wave)

        efe_by_label = {r["action"]: r["efe"] for r in ranked}
        true_efe = efe_by_label.get(true_label)
        efe_order = [r["action"] for r in ranked]
        efe_true_rank = (
            efe_order.index(true_label) + 1 if true_label in efe_order else None
        )
        sorted_efe = sorted(efe_by_label.values())
        efe_margin = (
            float(sorted_efe[1] - sorted_efe[0]) if len(sorted_efe) >= 2 else None
        )

        lam = self.planner._constraint_lambda()
        recomputed = {}
        for r in ranked:
            recomputed[r["action"]] = (
                self.planner.pragmatic_weight * r["pragmatic"]
                - self.planner.epistemic_weight * r["epistemic"]
                + lam * r["constraint_penalty"]
            )
        max_diff = max(
            abs(recomputed[a] - efe_by_label[a]) for a in efe_by_label
        )

        chosen_action = str(chosen.get("action")) if isinstance(chosen, dict) else str(action)
        return _base_out(
            task_id,
            arm=arm_id,
            status=STATUS_OK,
            functor_status=res.status,
            held_out_cos=getattr(res, "held_out_cos", None),
            identity_cos=getattr(res, "identity_cos", None),
            num_options=len(labels),
            true_label=true_label,
            true_efe=float(true_efe) if true_efe is not None else None,
            efe_true_rank=efe_true_rank,
            efe_margin=efe_margin,
            chosen_action=chosen_action,
            chosen_was_true=(chosen_action == true_label),
            explored=bool(chosen.get("explored", False)) if isinstance(chosen, dict) else False,
            decomposition=[
                {k: r[k] for k in (
                    "action", "efe", "pragmatic", "epistemic",
                    "constraint_penalty", "goal_distance", "rejected",
                )}
                for r in ranked
            ],
            vmap_agreement=vmap_agreement,
            decomposition_max_diff=max_diff,
            boundary_shape=list(boundary_batch.shape),
        )
